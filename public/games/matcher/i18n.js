let currentLang = localStorage.getItem("matcher-lang") || "en";
let activeLangCountry = localStorage.getItem("matcher-lang-country") || "";

function t(key, vars = {}) {
  const table = I18N[currentLang] || I18N.en;
  const fallback = I18N.en;
  let value = key.split(".").reduce((obj, part) => obj?.[part], table);
  if (value == null) value = key.split(".").reduce((obj, part) => obj?.[part], fallback);
  if (typeof value !== "string") return key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}

function applyTranslations() {
  document.title = t("title");
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });

  document.querySelectorAll("[data-i18n-pairs]").forEach((el) => {
    const n = el.getAttribute("data-i18n-pairs");
    el.textContent = t("pairsCount", { n });
  });

  const bar = document.getElementById("lang-bar");
  if (bar) {
    bar.setAttribute("aria-label", t("langBar"));
    renderLanguageBar();
  }
}

function countryFlagEmoji(code) {
  const iso = code === "uk" ? "gb" : code;
  return [...iso.toUpperCase()]
    .map((char) => String.fromCodePoint(127397 + char.charCodeAt(0)))
    .join("");
}

function languageLabel(code) {
  return LANGS.find((lang) => lang.code === code)?.label || code;
}

function countriesForLanguageBar() {
  const codes =
    typeof COUNTRY_ORDER !== "undefined" && COUNTRY_ORDER.length
      ? [...COUNTRY_ORDER]
      : Object.keys(COUNTRY_LANG);
  const englishNames = I18N.en?.countries || {};
  return codes.sort((a, b) => {
    const nameA = englishNames[a] || a;
    const nameB = englishNames[b] || b;
    return nameA.localeCompare(nameB, "en", { sensitivity: "base" });
  });
}

function canonicalCountryForLang(lang) {
  const preferred = {
    en: "uk",
    fr: "fr",
    es: "es",
    de: "de",
    it: "it",
    pt: "pt",
    pl: "pl",
    nl: "nl",
    hu: "hu",
    zh: "cn",
    ja: "jp",
    ko: "kr",
    hi: "in",
  };
  const preferredCountry = preferred[lang];
  if (preferredCountry && COUNTRY_LANG[preferredCountry] === lang) {
    return preferredCountry;
  }
  return countriesForLanguageBar().find((country) => COUNTRY_LANG[country] === lang) || "";
}

function renderLanguageBar() {
  const bar = document.getElementById("lang-bar");
  if (!bar) return;
  const escapeAttr = (value) =>
    String(value)
      .replace(/&/g, "&amp;")
      .replace(/"/g, "&quot;")
      .replace(/</g, "&lt;");
  const activeCountry =
    activeLangCountry && COUNTRY_LANG[activeLangCountry] === currentLang
      ? activeLangCountry
      : canonicalCountryForLang(currentLang);
  bar.innerHTML = countriesForLanguageBar()
    .map((country) => {
      const lang = COUNTRY_LANG[country] || "en";
      if (!I18N[lang]) return "";
      const name = t(`countries.${country}`);
      const label = escapeAttr(`${name} · ${languageLabel(lang)}`);
      const active = country === activeCountry ? " is-active" : "";
      return `<button type="button" class="lang-flag${active}" data-lang="${lang}" data-country="${country}" title="${label}" aria-label="${label}">${countryFlagEmoji(country)}</button>`;
    })
    .join("");
}

function setLanguage(code, countryCode = "") {
  if (!I18N[code]) return;
  currentLang = code;
  localStorage.setItem("matcher-lang", code);
  if (countryCode && COUNTRY_LANG[countryCode] === code) {
    activeLangCountry = countryCode;
    localStorage.setItem("matcher-lang-country", countryCode);
  } else if (!activeLangCountry || COUNTRY_LANG[activeLangCountry] !== code) {
    activeLangCountry = canonicalCountryForLang(code);
    localStorage.setItem("matcher-lang-country", activeLangCountry);
  }
  document.documentElement.lang = code;
  applyTranslations();
  window.dispatchEvent(new CustomEvent("languagechange", { detail: { code } }));
}

function initI18n() {
  renderLanguageBar();
  const bar = document.getElementById("lang-bar");
  if (bar) {
    bar.addEventListener("click", (event) => {
      const btn = event.target.closest("[data-lang]");
      if (!btn) return;
      setLanguage(btn.dataset.lang, btn.dataset.country || "");
    });
  }
  applyTranslations();
}
